#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const DEFAULT_KEYWORDS = [
  "submitDraft",
  "rescheduleSlot",
  "captchaPayload",
  "captcha-validate",
  "/captcha",
  "captchaToken",
  "getAvailableSlots",
  "getAvailableTsoSlot",
  "getTransportationType",
  "encryptedTso",
  "encryptedSettings",
  "intercept(t, r)",
  "FacilityMode",
  "User-Local-Time",
  "X-XSRF-TOKEN",
  "ActivityLog",
  "writeToActivityJournal",
  "subscribeToUserActivity",
  "postLoginMessage",
];

function readOption(name, fallback) {
  const index = process.argv.indexOf(name);
  if (index === -1 || index + 1 >= process.argv.length) return fallback;
  return process.argv[index + 1];
}

function readRepeatedOption(name) {
  const values = [];
  for (let i = 0; i < process.argv.length - 1; i += 1) {
    if (process.argv[i] === name) values.push(process.argv[i + 1]);
  }
  return values;
}

function mergeRanges(ranges) {
  if (ranges.length === 0) return [];
  ranges.sort((a, b) => a[0] - b[0]);

  const merged = [ranges[0]];
  for (const [start, end] of ranges.slice(1)) {
    const last = merged[merged.length - 1];
    if (start <= last[1] + 1) {
      last[1] = Math.max(last[1], end);
    } else {
      merged.push([start, end]);
    }
  }
  return merged;
}

function clampLine(line, maxChars) {
  if (line.length <= maxChars) return line;
  return `${line.slice(0, maxChars)} ... /* truncated */`;
}

const input = readOption("--input", "eopp_original.js");
const output = readOption("--output", "build/eopp_original_relevant.js");
const contextLines = Number(readOption("--context-lines", "35"));
const maxLineChars = Number(readOption("--max-line-chars", "3000"));
const keywords = [...DEFAULT_KEYWORDS, ...readRepeatedOption("--keyword")];

if (!fs.existsSync(input)) {
  console.error(`Input file not found: ${input}`);
  process.exit(1);
}

const lines = fs.readFileSync(input, "utf8").split(/\r?\n/);
const ranges = [];

for (let i = 0; i < lines.length; i += 1) {
  if (keywords.some((keyword) => lines[i].includes(keyword))) {
    ranges.push([
      Math.max(0, i - contextLines),
      Math.min(lines.length, i + contextLines + 1),
    ]);
  }
}

const merged = mergeRanges(ranges);
fs.mkdirSync(path.dirname(output), { recursive: true });

const out = [
  "// Generated by scripts/extract-eopp-original.mjs",
  `// Source: ${input}`,
  `// Keywords: ${keywords.join(", ")}`,
  `// Sections: ${merged.length}`,
  "",
];

for (let i = 0; i < merged.length; i += 1) {
  const [start, end] = merged[i];
  out.push("", `// ===== section ${i + 1}: lines ${start + 1}-${end} =====`);
  for (let lineNo = start; lineNo < end; lineNo += 1) {
    out.push(`// L${lineNo + 1}`, clampLine(lines[lineNo], maxLineChars));
  }
}

fs.writeFileSync(output, `${out.join("\n")}\n`, "utf8");
console.log(`Wrote ${output} (${merged.length} sections)`);
